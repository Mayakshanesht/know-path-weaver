/** Prepare a reviewed, transactional content migration. Never writes to a live database. */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { prepareQualityPlan } from './course-quality-plan.mjs';

export function renderQualityMigration(plan) {
  const literal = `'${JSON.stringify(plan).replace(/'/g, "''")}'::jsonb`;
  if (literal.includes('$quality$')) throw new Error('Editorial text contains the migration delimiter. Choose a different delimiter before writing SQL.');
  return `-- Generated by scripts/prepare-course-quality.mjs from reviewed editorial manifests.
-- The entire DO block is atomic. Audited values or their intended final state
-- must match; identity, type and attribution drift abort all changes.
-- Empty installations skip absent courses. Media and old attempt answer keys stay intact.
DO $quality$
DECLARE
  v_plan jsonb := ${literal};
  v_course jsonb; v_patch jsonb; v_quiz jsonb; v_question jsonb;
  v_course_id uuid; v_owner uuid; v_parent uuid; v_current text;
  v_type text; v_title text; v_published boolean; v_current_json jsonb;
  v_before jsonb; v_after jsonb; v_order integer;
BEGIN
  FOR v_course IN SELECT value FROM jsonb_array_elements(v_plan) LOOP
    v_course_id := (v_course->>'course_id')::uuid;
    SELECT is_published INTO v_published FROM public.courses WHERE id=v_course_id FOR UPDATE;
    IF NOT FOUND THEN CONTINUE; END IF;
    IF v_published IS NOT TRUE THEN RAISE EXCEPTION 'Editorial course is no longer published: %',v_course_id; END IF;
    FOR v_patch IN SELECT value FROM jsonb_array_elements(COALESCE(v_course->'capsule_updates','[]')) LOOP
      SELECT lp.course_id,c.learning_path_id,c.description INTO v_owner,v_parent,v_current
        FROM public.capsules c JOIN public.learning_paths lp ON lp.id=c.learning_path_id
        WHERE c.id=(v_patch->>'id')::uuid FOR UPDATE OF c,lp;
      IF NOT FOUND OR v_owner IS DISTINCT FROM v_course_id OR v_parent IS DISTINCT FROM (v_patch->>'learning_path_id')::uuid THEN
        RAISE EXCEPTION 'Editorial lesson is missing or moved: %',v_patch->>'id';
      END IF;
      IF v_current IS NOT DISTINCT FROM (v_patch->>'before_description') THEN
        UPDATE public.capsules SET description=v_patch->>'description' WHERE id=(v_patch->>'id')::uuid;
      ELSIF v_current IS DISTINCT FROM (v_patch->>'description') THEN RAISE EXCEPTION 'Lesson edited since audit: %',v_patch->>'id'; END IF;
    END LOOP;
    FOR v_patch IN SELECT value FROM jsonb_array_elements(COALESCE(v_course->'content_updates','[]')) LOOP
      SELECT lp.course_id,cc.capsule_id,cc.content_type,cc.title,cc.content_value INTO v_owner,v_parent,v_type,v_title,v_current
        FROM public.capsule_content cc JOIN public.capsules c ON c.id=cc.capsule_id
        JOIN public.learning_paths lp ON lp.id=c.learning_path_id
        WHERE cc.id=(v_patch->>'id')::uuid FOR UPDATE OF cc,c,lp;
      IF NOT FOUND OR v_owner IS DISTINCT FROM v_course_id OR v_parent IS DISTINCT FROM (v_patch->>'capsule_id')::uuid
        OR v_type IS DISTINCT FROM 'text' OR v_title IS DISTINCT FROM (v_patch->>'before_title') THEN
        RAISE EXCEPTION 'Editorial text attribution or type changed: %',v_patch->>'id';
      END IF;
      IF v_current IS NOT DISTINCT FROM (v_patch->>'before_content_value') THEN
        UPDATE public.capsule_content SET content_value=v_patch->>'content_value' WHERE id=(v_patch->>'id')::uuid;
      ELSIF v_current IS DISTINCT FROM (v_patch->>'content_value') THEN RAISE EXCEPTION 'Text edited since audit: %',v_patch->>'id'; END IF;
    END LOOP;
    FOR v_patch IN SELECT value FROM jsonb_array_elements(COALESCE(v_course->'question_updates','[]')) LOOP
      SELECT q.course_id,qq.quiz_id,qq.question_type,jsonb_build_object('question_text',qq.question_text,'options',qq.options,
        'correct_answer',qq.correct_answer,'explanation',qq.explanation) INTO v_owner,v_parent,v_type,v_current_json
        FROM public.quiz_questions qq JOIN public.quizzes q ON q.id=qq.quiz_id
        WHERE qq.id=(v_patch->>'id')::uuid FOR UPDATE OF qq,q;
      IF NOT FOUND OR v_owner IS DISTINCT FROM v_course_id OR v_parent IS DISTINCT FROM (v_patch->>'quiz_id')::uuid
        OR v_type IS DISTINCT FROM (v_patch->>'question_type') THEN
        RAISE EXCEPTION 'Editorial question attribution or type changed: %',v_patch->>'id';
      END IF;
      v_before := jsonb_build_object('question_text',v_patch->'before_question_text','options',v_patch->'before_options',
        'correct_answer',v_patch->'before_correct_answer','explanation',v_patch->'before_explanation');
      v_after := jsonb_build_object('question_text',v_patch->'question_text','options',v_patch->'options',
        'correct_answer',v_patch->'correct_answer','explanation',v_patch->'explanation');
      IF v_current_json = v_before THEN
        UPDATE public.quiz_questions SET question_text=v_patch->>'question_text',options=v_patch->'options',
          correct_answer=v_patch->'correct_answer',explanation=v_patch->>'explanation' WHERE id=(v_patch->>'id')::uuid;
      ELSIF v_current_json IS DISTINCT FROM v_after THEN RAISE EXCEPTION 'Question edited since audit: %',v_patch->>'id'; END IF;
    END LOOP;
    FOR v_patch IN SELECT value FROM jsonb_array_elements(v_course->'additions') LOOP
      SELECT lp.course_id INTO v_owner FROM public.capsules c JOIN public.learning_paths lp ON lp.id=c.learning_path_id
        WHERE c.id=(v_patch->>'target_capsule_id')::uuid FOR UPDATE OF c,lp;
      IF NOT FOUND OR v_owner IS DISTINCT FROM v_course_id THEN RAISE EXCEPTION 'Study-guide target is missing or moved: %',v_patch->>'target_capsule_id'; END IF;
      SELECT lp.course_id,cc.capsule_id,cc.content_type,cc.title,cc.content_value INTO v_owner,v_parent,v_type,v_title,v_current
        FROM public.capsule_content cc JOIN public.capsules c ON c.id=cc.capsule_id
        JOIN public.learning_paths lp ON lp.id=c.learning_path_id
        WHERE cc.id=(v_patch->>'id')::uuid FOR UPDATE OF cc,c,lp;
      IF FOUND THEN
        IF v_owner IS DISTINCT FROM v_course_id OR v_parent IS DISTINCT FROM (v_patch->>'target_capsule_id')::uuid
          OR v_type IS DISTINCT FROM 'text' OR v_title IS DISTINCT FROM (v_patch->>'title')
          OR v_current IS DISTINCT FROM (v_patch->>'content_value') THEN
          RAISE EXCEPTION 'Study guide attribution or content changed after release: %',v_patch->>'id';
        END IF;
      ELSE
        SELECT COALESCE(max(order_index)+1,0) INTO v_order FROM public.capsule_content WHERE capsule_id=(v_patch->>'target_capsule_id')::uuid;
        INSERT INTO public.capsule_content(id,capsule_id,content_type,title,content_value,order_index,metadata)
          VALUES((v_patch->>'id')::uuid,(v_patch->>'target_capsule_id')::uuid,'text',v_patch->>'title',v_patch->>'content_value',v_order,
            '{"editorial_release":"2026-10-19","kind":"study_guide"}'::jsonb);
      END IF;
    END LOOP;
    FOR v_quiz IN SELECT value FROM jsonb_array_elements(v_course->'quizzes') LOOP
      SELECT lp.course_id INTO v_owner FROM public.capsules c JOIN public.learning_paths lp ON lp.id=c.learning_path_id
        WHERE c.id=(v_quiz->>'capsule_id')::uuid FOR UPDATE OF c,lp;
      IF NOT FOUND OR v_owner IS DISTINCT FROM v_course_id THEN RAISE EXCEPTION 'Quiz target is missing or moved: %',v_quiz->>'capsule_id'; END IF;
      SELECT jsonb_build_object('course_id',course_id,'capsule_id',capsule_id,'title',title,'quiz_type',quiz_type,
        'is_graded',is_graded,'is_published',is_published,'max_attempts',max_attempts) INTO v_current_json
        FROM public.quizzes WHERE id=(v_quiz->>'id')::uuid FOR UPDATE;
      IF FOUND THEN
        v_after := jsonb_build_object('course_id',v_course_id,'capsule_id',(v_quiz->>'capsule_id')::uuid,'title',v_quiz->>'title',
          'quiz_type','quiz','is_graded',false,'is_published',true,'max_attempts',NULL);
        IF v_current_json IS DISTINCT FROM v_after THEN RAISE EXCEPTION 'Practice quiz attribution or settings changed: %',v_quiz->>'id'; END IF;
      ELSE
        INSERT INTO public.quizzes(id,course_id,capsule_id,title,description,quiz_type,is_graded,passing_score,max_attempts,is_published,order_index)
          VALUES((v_quiz->>'id')::uuid,v_course_id,(v_quiz->>'capsule_id')::uuid,v_quiz->>'title',
            'Formative practice for the study guide. Read the explanation and retry; this does not replace the course assessment.',
            'quiz',false,70,NULL,true,1000);
      END IF;
      FOR v_question IN SELECT value FROM jsonb_array_elements(v_quiz->'questions') LOOP
        SELECT q.course_id,qq.quiz_id,qq.question_type,jsonb_build_object('question_text',qq.question_text,'options',qq.options,
          'correct_answer',qq.correct_answer,'explanation',qq.explanation,'points',qq.points,'order_index',qq.order_index)
          INTO v_owner,v_parent,v_type,v_current_json FROM public.quiz_questions qq JOIN public.quizzes q ON q.id=qq.quiz_id
          WHERE qq.id=(v_question->>'id')::uuid FOR UPDATE OF qq,q;
        v_after := jsonb_build_object('question_text',v_question->'question_text','options',v_question->'options',
          'correct_answer',v_question->'correct_answer','explanation',v_question->'explanation','points',1,'order_index',(v_question->>'order_index')::int);
        IF FOUND THEN
          IF v_owner IS DISTINCT FROM v_course_id OR v_parent IS DISTINCT FROM (v_quiz->>'id')::uuid
            OR v_type IS DISTINCT FROM 'mcq' OR v_current_json IS DISTINCT FROM v_after THEN
            RAISE EXCEPTION 'Practice question attribution or content changed after release: %',v_question->>'id';
          END IF;
        ELSE
          INSERT INTO public.quiz_questions(id,quiz_id,question_type,question_text,options,correct_answer,explanation,points,order_index)
            VALUES((v_question->>'id')::uuid,(v_quiz->>'id')::uuid,'mcq',v_question->>'question_text',v_question->'options',
              v_question->'correct_answer',v_question->>'explanation',1,(v_question->>'order_index')::int);
        END IF;
      END LOOP;
    END LOOP;
  END LOOP;
END;
$quality$;
`;
}

function main(args) {
  const snapshotIndex = args.indexOf('--snapshot');
  const snapshotPath = args[snapshotIndex + 1];
  if (snapshotIndex < 0 || !snapshotPath || snapshotPath.startsWith('--')) {
    throw new Error('Usage: node scripts/prepare-course-quality.mjs --snapshot backup/course-quality-20261019.json [--write]');
  }
  const snapshot = JSON.parse(readFileSync(snapshotPath, 'utf8'));
  const manifests = ['content/catalog-core-enhancements.json', 'content/catalog-applied-enhancements.json']
    .map(path => JSON.parse(readFileSync(path, 'utf8')));
  const plan = prepareQualityPlan(manifests, snapshot);
  console.log(JSON.stringify(plan.map(course => ({ course: course.course_title,
    descriptions: course.capsule_updates.length, correctedTexts: course.content_updates.length,
    correctedQuestions: course.question_updates.length, studyGuides: course.additions.length,
    formativeQuestions: course.quizzes.reduce((total, quiz) => total + quiz.questions.length, 0),
  })), null, 2));
  if (!args.includes('--write')) return;
  const destination = 'supabase/migrations/20261019020000_course_quality_improvements.sql';
  writeFileSync(destination, renderQualityMigration(plan));
  console.log(`Prepared ${destination}. No database was changed.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
